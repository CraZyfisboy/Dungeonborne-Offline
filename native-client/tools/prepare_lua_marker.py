"""Wrap the unmodified startup bytecode with a local diagnostic marker.

Only adds a separate diagnostics pak to the isolated native runtime. The marker
is not an offline implementation and does not change the original Lua logic.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from prepare_native_probe import pak

parser = argparse.ArgumentParser()
parser.add_argument('--player', action='store_true', help='include only player code in the Lua pak')
options = parser.parse_args()
source_root = ROOT / 'analysis/raw-lua'
source = source_root / 'Dungeonborne/Content/Script/Main.lua'
code = source.read_bytes()
if not code.startswith(b'\x1bLua\x54'):
    raise ValueError('unexpected startup bytecode')
# Fixed three-digit decimal escapes preserve every byte; no external Lua
# compiler or untrusted generated bytecode is introduced.
literal = ''.join('\\%03d' % b for b in code)
wrapper = '''local function mark(message)
  if io and io.open then
    local f = io.open("offline-lua-probe.txt", "a")
    if f then f:write(message .. "\\n"); f:close() end
  end
end
mark("startup Main wrapper reached")
local original = "''' + literal + '''"
local run, err = load(original, "@OriginalGameMain.lua", "b", _ENV)
if not run then mark("load failed: " .. tostring(err)); error(err) end
mark("original Main loaded")
local result = run(...)
mark("original Main returned")
local ok, err = pcall(function() require("OfflineProbe.Boot").start(mark) end)
if not ok then mark("boot observer failed: " .. tostring(err)) end
return result
'''
relative = 'Dungeonborne/Content/Script/Main.lua'
dest = ROOT / 'artifacts/pakchunk10000-OfflineDiagnostics_P.pak'
files = {relative: wrapper.encode('ascii')}
for module in ('BP_InventoryStorage','BP_InventoryPageAddTab','BP_InventoryCharacterSection','BP_InventorySlot','BP_Common_ItemEntry'):
    name = f'Dungeonborne/Content/Script/Inventory/{module}.lua'
    original = (source_root / name).read_bytes()
    if not original.startswith(b'\x1bLua\x54'):
        raise ValueError('expected original inventory bytecode: ' + name)
    literal = ''.join('\\%03d' % b for b in original)
    patch = (f'local original = assert(load("{literal}", "@Original{module}.lua", "b", _ENV))\n'
             f'return require("OfflineProbe.StorageUI").apply(original(...), "{module}")\n')
    files[name] = patch.encode('ascii')
client = (ROOT / 'adapter/integration-command.lua').read_bytes()
if options.player:
    development_start = b'\nlocal function check_backpack_layout('
    client = client.split(development_start, 1)[0]
files['Dungeonborne/Content/Script/OfflineProbe/Client.lua'] = client
for file in (ROOT / 'mods').rglob('*.lua'):
    if file.name == 'LootUI.lua' or (options.player and file.name == 'WolfGroundCheck.lua'):
        continue  # Retained research; original pickup succeeds at a valid distance.
    files['Dungeonborne/Content/Script/' + file.relative_to(ROOT / 'mods').as_posix()] = file.read_bytes()
dest.write_bytes(pak(files))
payload = ROOT / 'payload-lua-marker' / relative
payload.parent.mkdir(parents=True, exist_ok=True)
payload.write_bytes(wrapper.encode('ascii'))
for path, data in files.items():
    target = ROOT / 'payload-lua-marker' / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
report = dict(original_main_sha256=hashlib.sha256(code).hexdigest(),
              marker_package=str(dest), package_sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),
              purpose='native offline research mod; original startup bytecode preserved verbatim',
              expected_payloads=sorted(files),
              independently_read_back=False)
(ROOT / 'reports/lua-marker-preparation.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
print('Prepared diagnostic wrapper; original bytecode size:', len(code))
